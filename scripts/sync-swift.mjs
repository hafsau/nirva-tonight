// Copies NirvaKit's view sources into the web app (for the Under the hood panel
// and /system), and records which SwiftUI renders exist in web/public/swiftui.
// Renders come from CI (iOS Simulator) via `gh run download`, or locally from
// `swift run nirva-render` (macOS) with RENDER_SOURCE=macos.
import { readFileSync, writeFileSync, readdirSync, existsSync, copyFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const kit = join(root, "swift/NirvaKit/Sources/NirvaKit");
const FILES = ["Views/Blocks.swift", "Views/DayArcShape.swift", "Views/ReflectionScreen.swift", "Design/Primitives.swift", "Replay/ReflectionReplay.swift", "Stream/Snapshot.swift", "Gen/Tokens.swift"];
const sources = Object.fromEntries(FILES.map((f) => [f, readFileSync(join(kit, f), "utf8")]));

const pub = join(root, "web/public/swiftui");
mkdirSync(pub, { recursive: true });
const from = process.argv[2];
if (from) {
  for (const f of readdirSync(from).filter((f) => f.endsWith(".png"))) copyFileSync(join(from, f), join(pub, f));
  const manifest = existsSync(join(from, "manifest.json"))
    ? JSON.parse(readFileSync(join(from, "manifest.json"), "utf8"))
    : { source: process.env.RENDER_SOURCE ?? "macos", note: "Rendered with SwiftUI ImageRenderer on macOS (no Xcode). CI replaces these with iOS Simulator renders." };
  // CI reports the runtime as e.g. "iOS-26-5"; show it as "iOS 26.5".
  if (manifest.os) manifest.os = manifest.os.replace(/^iOS-(\d+)-(\d+)$/, "iOS $1.$2");
  writeFileSync(join(pub, "manifest.json"), JSON.stringify(manifest, null, 2));
}
const manifest = existsSync(join(pub, "manifest.json")) ? JSON.parse(readFileSync(join(pub, "manifest.json"), "utf8")) : null;
const renders = readdirSync(pub).filter((f) => f.endsWith(".png")).map((f) => f.replace(".png", "")).sort();

writeFileSync(
  join(root, "web/lib/gen/swift.ts"),
  "// Generated by scripts/sync-swift.mjs. Do not edit.\n" +
    `export const SWIFT_SOURCES: Record<string, string> = ${JSON.stringify(sources, null, 2)};\n` +
    `export const SWIFT_RENDERS: string[] = ${JSON.stringify(renders)};\n` +
    `export const SWIFT_MANIFEST: { source: string; note?: string; sha?: string; device?: string; os?: string; xcode?: string; date?: string } | null = ${JSON.stringify(manifest)};\n`,
);
console.log(`synced ${FILES.length} Swift files, ${renders.length} renders (${manifest?.source ?? "none"})`);

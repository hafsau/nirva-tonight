// tokens/tokens.json -> web/app/tokens.css, web/lib/gen/tokens.ts, and
// swift/NirvaKit/Sources/NirvaKit/Gen/Tokens.swift. Components on both platforms
// read only these names; CLAUDE.md and the lint hook reject raw values.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(join(root, "tokens/tokens.json"), "utf8"));
const HEADER = "Generated by scripts/tokens.mjs from tokens/tokens.json. Do not edit.";
const write = (rel, text) => {
  mkdirSync(dirname(join(root, rel)), { recursive: true });
  writeFileSync(join(root, rel), text);
  console.log("wrote", rel);
};
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

// ---------- CSS ----------
let css = `/* ${HEADER} */\n:root {\n`;
for (const [k, v] of Object.entries(t.color)) css += `  --color-${kebab(k)}: ${v.value};\n`;
for (const [k, v] of Object.entries(t.space)) css += `  --space-${k}: ${v}px;\n`;
for (const [k, v] of Object.entries(t.radius)) css += `  --radius-${k}: ${v}px;\n`;
for (const [k, v] of Object.entries(t.motion)) css += `  --motion-${k}: ${v.duration}ms;\n`;
css += "}\n\n";
for (const [k, v] of Object.entries(t.type)) {
  const fam = t.family[v.family];
  css += `.type-${k} {\n  font-family: ${fam.css};\n  font-size: ${v.size}px;\n  line-height: ${v.line}px;\n  font-weight: ${v.weight};\n`;
  if (fam.italic) css += "  font-style: italic;\n";
  if (v.tracking) css += `  letter-spacing: ${v.tracking}em;\n`;
  if (v.uppercase) css += "  text-transform: uppercase;\n";
  css += "}\n";
}
write("web/app/tokens.css", css);
// WCAG contrast of each solid color against mist, for the /system table.
const lum = (hex) => {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
const contrast = Object.fromEntries(
  Object.entries(t.color)
    .filter(([, v]) => v.value.startsWith("#"))
    .map(([k, v]) => {
      const [a, b] = [lum(v.value), lum(t.color.mist.value)];
      return [k, Math.round(((Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05)) * 100) / 100];
    }),
);
write("web/lib/gen/tokens.ts", `// ${HEADER}\nexport const TOKENS = ${JSON.stringify(t, null, 2)} as const;\nexport const CONTRAST_ON_MIST: Record<string, number> = ${JSON.stringify(contrast)};\n`);

// ---------- Swift ----------
function swiftColor(v) {
  const rgba = v.match(/rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/);
  if (rgba) {
    const [, r, g, b, a] = rgba;
    return `Color(.sRGB, red: ${(r / 255).toFixed(4)}, green: ${(g / 255).toFixed(4)}, blue: ${(b / 255).toFixed(4)}, opacity: ${a})`;
  }
  const h = v.replace("#", "");
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
  return `Color(.sRGB, red: ${r.toFixed(4)}, green: ${g.toFixed(4)}, blue: ${b.toFixed(4)})`;
}

let sw = `// ${HEADER}\n\nimport SwiftUI\n\npublic enum Tokens {\n`;
sw += "    public enum ColorToken {\n";
for (const [k, v] of Object.entries(t.color)) sw += `        /// ${v.use}\n        public static let ${k} = ${swiftColor(v.value)}\n`;
sw += "    }\n\n    public enum Space {\n";
for (const [k, v] of Object.entries(t.space)) sw += `        public static let ${k}: CGFloat = ${v}\n`;
sw += "    }\n\n    public enum Radius {\n";
for (const [k, v] of Object.entries(t.radius)) sw += `        public static let ${k}: CGFloat = ${v}\n`;
sw += "    }\n\n    public enum Motion {\n";
for (const [k, v] of Object.entries(t.motion)) {
  sw += `        /// ${v.use}\n        public static let ${k}: Animation = `;
  sw += v.bounce !== undefined ? `.spring(duration: ${v.duration / 1000}, bounce: ${v.bounce})\n` : `.easeInOut(duration: ${v.duration / 1000})\n`;
}
sw += "    }\n}\n\n";
sw += "/// Type styles scale with Dynamic Type through relativeTo:, so AX sizes work without per-view code.\npublic enum TypeStyle: CaseIterable, Sendable {\n";
sw += `    case ${Object.keys(t.type).join(", ")}\n\n`;
sw += "    public var font: Font {\n        switch self {\n";
for (const [k, v] of Object.entries(t.type)) {
  const fam = t.family[v.family];
  // Static instances, so weight is picked by PostScript name, not .weight().
  sw += `        case .${k}: Font.custom("${fam.swift[String(v.weight)]}", size: ${v.size}, relativeTo: .${v.swiftRelativeTo})\n`;
}
sw += "        }\n    }\n\n    public var lineSpacing: CGFloat {\n        switch self {\n";
// SwiftUI adds lineSpacing on top of the face's natural line height, so subtract
// that per family (Nunito's is tall, Libre Baskerville's is close to 1.24).
const NATURAL = { serif: 1.24, serifItalic: 1.24, sans: 1.364, label: 1.364, mono: 1.164 };
for (const [k, v] of Object.entries(t.type)) sw += `        case .${k}: ${Math.max(0, v.line - v.size * NATURAL[v.family]).toFixed(1)}\n`;
sw += "        }\n    }\n\n    public var tracking: CGFloat {\n        switch self {\n";
for (const [k, v] of Object.entries(t.type)) sw += `        case .${k}: ${v.tracking ? (v.tracking * v.size).toFixed(2) : 0}\n`;
sw += "        }\n    }\n\n    public var uppercased: Bool {\n        switch self {\n";
for (const [k, v] of Object.entries(t.type)) sw += `        case .${k}: ${v.uppercase ? "true" : "false"}\n`;
sw += "        }\n    }\n}\n";
write("swift/NirvaKit/Sources/NirvaKit/Gen/Tokens.swift", sw);

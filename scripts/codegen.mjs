// One schema, two platforms. Reads schema/reflection.schema.json and writes:
//   web/lib/gen/schema.ts                              TypeScript types
//   swift/NirvaKit/Sources/NirvaKit/Gen/Reflection.swift   Codable structs
//   swift/NirvaKit/Sources/NirvaKit/Gen/Generable.swift    @Generable mirror (compiled when NIRVA_GENERABLE is set)
// It also copies the fixture into both packages so web and SwiftUI replay the same night.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(readFileSync(join(root, "schema/reflection.schema.json"), "utf8"));
const HEADER = "// Generated by scripts/codegen.mjs from schema/reflection.schema.json. Do not edit.\n";

const cap = (s) => s[0].toUpperCase() + s.slice(1);
const out = (rel, text) => {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
  console.log("wrote", rel);
};

// ---------- TypeScript ----------
function tsType(t) {
  if (typeof t === "string") return { string: "string", bool: "boolean", int: "number", double: "number" }[t] ?? t;
  if (t.enum) return t.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (t.array) return `${wrap(tsType(t.array))}[]`;
  if (t.ref) return t.ref;
  if (t.optional) return tsType(t.optional);
  throw new Error(`unknown type ${JSON.stringify(t)}`);
}
const wrap = (s) => (s.includes("|") ? `(${s})` : s);

let ts = HEADER + "\n";
for (const [name, def] of Object.entries(schema.types)) {
  if (def.doc) ts += `/** ${def.doc} */\n`;
  const kind = Object.entries(schema.unions).find(([, u]) => Object.values(u.cases).includes(name));
  ts += `export interface ${name} {\n`;
  if (kind) {
    const [, u] = kind;
    const tag = Object.entries(u.cases).find(([, n]) => n === name)[0];
    ts += `  ${u.tag}: ${JSON.stringify(tag)};\n`;
  }
  for (const [field, type, doc] of def.fields) {
    if (doc) ts += `  /** ${doc} */\n`;
    ts += `  ${field}${type.optional ? "?" : ""}: ${tsType(type)};\n`;
  }
  ts += "}\n\n";
}
for (const [name, u] of Object.entries(schema.unions)) {
  ts += `export type ${name} = ${Object.values(u.cases).join(" | ")};\n`;
  ts += `export type ${name}Kind = ${name}["${u.tag}"];\n\n`;
}
// Field order is part of the contract: the replay reveals fields in this order.
ts += "/** Declared field order per type. Streaming fills fields in this order. */\n";
ts += `export const FIELD_ORDER = ${JSON.stringify(
  Object.fromEntries(Object.entries(schema.types).map(([n, d]) => [n, d.fields.map((f) => f[0])])),
  null,
  2,
)} as const;\n`;
ts += `export const UNION_CASES = ${JSON.stringify(schema.unions.Block.cases)} as const;\n`;
out("web/lib/gen/schema.ts", ts);

// ---------- Swift ----------
const SWIFT_KEYWORDS = new Set(["in", "is", "as", "default", "case", "func", "var", "let", "self", "Type", "protocol", "extension", "struct", "class", "enum", "repeat", "return", "where", "operator"]);
const swiftName = (s) => (SWIFT_KEYWORDS.has(s) ? `\`${s}\`` : s);

function swiftType(t, owner, field, nested) {
  if (typeof t === "string") return { string: "String", bool: "Bool", int: "Int", double: "Double" }[t] ?? t;
  if (t.enum) {
    const n = cap(field);
    nested.push({ name: n, cases: t.enum });
    return n;
  }
  if (t.array) return `[${swiftType(t.array, owner, field, nested)}]`;
  if (t.ref) return t.ref;
  if (t.optional) return `${swiftType(t.optional, owner, field, nested)}?`;
  throw new Error(`unknown type ${JSON.stringify(t)}`);
}

let sw = HEADER + "\nimport Foundation\n\n";
for (const [name, def] of Object.entries(schema.types)) {
  const nested = [];
  const fields = def.fields.map(([f, t, doc]) => ({ f, t: swiftType(t, name, f, nested), doc }));
  if (def.doc) sw += `/// ${def.doc}\n`;
  sw += `public struct ${name}: Codable, Hashable, Sendable {\n`;
  for (const e of nested) {
    sw += `    public enum ${e.name}: String, Codable, Hashable, Sendable, CaseIterable {\n`;
    sw += `        case ${e.cases.map(swiftName).join(", ")}\n    }\n\n`;
  }
  for (const { f, t, doc } of fields) {
    if (doc) sw += `    /// ${doc}\n`;
    sw += `    public var ${swiftName(f)}: ${t}\n`;
  }
  sw += `\n    public init(${fields.map(({ f, t }) => `${f}: ${t}${t.endsWith("?") ? " = nil" : ""}`).join(", ")}) {\n`;
  for (const { f } of fields) sw += `        self.${swiftName(f)} = ${swiftName(f)}\n`;
  sw += "    }\n}\n\n";
}
for (const [name, u] of Object.entries(schema.unions)) {
  const cases = Object.entries(u.cases);
  sw += `/// Tagged by "${u.tag}" in JSON. Exhaustive, so a new block kind is a compile error in every view that switches on it.\n`;
  sw += `public enum ${name}: Codable, Hashable, Sendable, Identifiable {\n`;
  for (const [tag, type] of cases) sw += `    case ${tag}(${type})\n`;
  sw += `\n    private enum TagKey: String, CodingKey { case ${u.tag} }\n\n`;
  sw += `    public init(from decoder: Decoder) throws {\n        let c = try decoder.container(keyedBy: TagKey.self)\n        switch try c.decode(String.self, forKey: .${u.tag}) {\n`;
  for (const [tag, type] of cases) sw += `        case "${tag}": self = .${tag}(try ${type}(from: decoder))\n`;
  sw += `        case let other: throw DecodingError.dataCorruptedError(forKey: .${u.tag}, in: c, debugDescription: "Unknown ${name} \\(other)")\n        }\n    }\n\n`;
  sw += `    public func encode(to encoder: Encoder) throws {\n        var c = encoder.container(keyedBy: TagKey.self)\n        switch self {\n`;
  for (const [tag] of cases) sw += `        case .${tag}(let value): try c.encode("${tag}", forKey: .${u.tag}); try value.encode(to: encoder)\n`;
  sw += `        }\n    }\n\n    public var id: String {\n        switch self {\n`;
  for (const [tag] of cases) sw += `        case .${tag}(let value): value.id\n`;
  sw += `        }\n    }\n}\n`;
}

// ---------- Partial (snapshot) types ----------
// The shape a stream snapshot decodes into: every field optional, nested types
// partial too. Same idea as Foundation Models' PartiallyGenerated.
function partialType(t, field) {
  if (typeof t === "string") return schema.types[t] || schema.unions[t] ? `${t}.Partial` : { string: "String", bool: "Bool", int: "Int", double: "Double" }[t];
  if (t.enum) return cap(field);
  if (t.array) return `[${partialType(t.array, field)}]`;
  if (t.ref) return `${t.ref}.Partial`;
  if (t.optional) return partialType(t.optional, field);
}
sw += "\n// MARK: - Partial snapshots\n\n";
for (const [name, def] of Object.entries(schema.types)) {
  sw += `extension ${name} {\n    public struct Partial: Decodable, Hashable, Sendable {\n`;
  for (const [f, t] of def.fields) sw += `        public var ${swiftName(f)}: ${partialType(t, f)}?\n`;
  sw += "    }\n}\n\n";
}
for (const [name, u] of Object.entries(schema.unions)) {
  const cases = Object.entries(u.cases);
  sw += `extension ${name} {\n    public enum Partial: Decodable, Hashable, Sendable {\n`;
  for (const [tag, type] of cases) sw += `        case ${tag}(${type}.Partial)\n`;
  sw += `\n        private enum TagKey: String, CodingKey { case ${u.tag} }\n\n`;
  sw += `        public init(from decoder: Decoder) throws {\n            let c = try decoder.container(keyedBy: TagKey.self)\n            switch try c.decode(String.self, forKey: .${u.tag}) {\n`;
  for (const [tag, type] of cases) sw += `            case "${tag}": self = .${tag}(try ${type}.Partial(from: decoder))\n`;
  sw += `            case let other: throw DecodingError.dataCorruptedError(forKey: .${u.tag}, in: c, debugDescription: "Unknown ${name} \\(other)")\n            }\n        }\n    }\n}\n`;
}
out("swift/NirvaKit/Sources/NirvaKit/Gen/Reflection.swift", sw);

// ---------- @Generable mirror ----------
// What you'd hand to LanguageModelSession.streamResponse(generating:). Field order
// is generation order, so @Guide text carries the same rules as the schema docs.
function genType(t, field, nested) {
  if (typeof t === "string") return { string: "String", bool: "Bool", int: "Int", double: "Double" }[t] ?? t;
  if (t.enum) {
    nested.push({ name: cap(field), cases: t.enum });
    return cap(field);
  }
  if (t.array) return `[${genType(t.array, field, nested)}]`;
  if (t.ref) return `G${t.ref}`;
  if (t.optional) return `${genType(t.optional, field, nested)}?`;
  return t;
}
const refName = (n) => (schema.types[n] || schema.unions[n] ? `G${n}` : n);
let gen = HEADER + "\n#if NIRVA_GENERABLE\nimport FoundationModels\n\n";
for (const [name, def] of Object.entries(schema.types)) {
  const nested = [];
  const fields = def.fields.map(([f, t, doc]) => ({ f, t: genType(t, f, nested).replace(/\bG?([A-Z]\w+)\b/g, (m, n) => (schema.types[n] || schema.unions[n] ? `G${n}` : m)), doc }));
  gen += `@available(iOS 26.0, macOS 26.0, *)\n@Generable${def.doc ? `(description: ${JSON.stringify(def.doc)})` : ""}\npublic struct G${name} {\n`;
  for (const e of nested) gen += `    @Generable public enum ${e.name}: String { case ${e.cases.map(swiftName).join(", ")} }\n`;
  for (const { f, t, doc } of fields) {
    if (doc) gen += `    @Guide(description: ${JSON.stringify(doc)})\n`;
    gen += `    public var ${swiftName(f)}: ${t}\n`;
  }
  gen += "}\n\n";
}
for (const [name, u] of Object.entries(schema.unions)) {
  gen += `@available(iOS 26.0, macOS 26.0, *)\n@Generable\npublic enum G${name} {\n`;
  for (const [tag, type] of Object.entries(u.cases)) gen += `    case ${tag}(${refName(type)})\n`;
  gen += "}\n";
}
gen += "#endif\n";
out("swift/NirvaKit/Sources/NirvaKit/Gen/Generable.swift", gen);

// ---------- fixture copies ----------
copyFileSync(join(root, "schema/reflection.schema.json"), join(root, "web/lib/gen/reflection.schema.json"));
for (const dest of ["web/lib/gen/tonight.json", "swift/NirvaKit/Sources/NirvaKit/Resources/tonight.json"]) {
  mkdirSync(dirname(join(root, dest)), { recursive: true });
  copyFileSync(join(root, "fixtures/tonight.json"), join(root, dest));
  console.log("copied fixtures/tonight.json ->", dest);
}

// Turns tonight's finished reflection into the stream a model would have produced:
// fields in declared order, strings in small word chunks, a `done` mark when each
// field closes. Each line is a patch; applying patches 0..n gives snapshot n, the
// same shape Foundation Models hands SwiftUI as PartiallyGenerated content.
// Web replay and the SwiftUI tests both read fixtures/tonight.stream.jsonl.
import { readFileSync, writeFileSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(readFileSync(join(root, "schema/reflection.schema.json"), "utf8"));
const fixture = JSON.parse(readFileSync(join(root, "fixtures/tonight.json"), "utf8"));

const patches = [];
const emit = (p) => patches.push(p);

function chunks(text) {
  const words = text.split(" ");
  const out = [];
  for (let i = 0; i < words.length; i += 3) out.push(words.slice(0, i + 3).join(" "));
  return out;
}

function walk(value, type, path) {
  if (type === "string") {
    const parts = chunks(value);
    parts.forEach((v, i) => emit(i === parts.length - 1 ? { p: path, v, done: true } : { p: path, v }));
    return;
  }
  if (typeof type === "string" && schema.types[type]) return walkStruct(value, type, path);
  if (typeof type === "string" && schema.unions[type]) {
    const u = schema.unions[type];
    const caseType = u.cases[value[u.tag]];
    emit({ p: [...path, u.tag], v: value[u.tag], done: true });
    return walkStruct(value, caseType, path);
  }
  if (typeof type === "string" || type.enum) return emit({ p: path, v: value, done: true });
  if (type.optional) return value === undefined ? undefined : walk(value, type.optional, path);
  if (type.ref) return walk(value, type.ref, path);
  if (type.array) {
    emit({ p: path, v: [] });
    value.forEach((item, i) => walk(item, type.array, [...path, i]));
    return emit({ p: path, done: true });
  }
  throw new Error(`unknown type ${JSON.stringify(type)}`);
}

function walkStruct(value, typeName, path) {
  for (const [field, type] of schema.types[typeName].fields) {
    if (value[field] === undefined) continue;
    walk(value[field], type, [...path, field]);
  }
  if (path.length) emit({ p: path, done: true });
}

walk(fixture.reflection, "Reflection", []);
const text = patches.map((p) => JSON.stringify(p)).join("\n") + "\n";
writeFileSync(join(root, "fixtures/tonight.stream.jsonl"), text);
copyFileSync(join(root, "fixtures/tonight.stream.jsonl"), join(root, "swift/NirvaKit/Sources/NirvaKit/Resources/tonight.stream.jsonl"));
writeFileSync(
  join(root, "web/lib/gen/stream.ts"),
  "// Generated by scripts/snapshots.mjs from fixtures/tonight.json. Do not edit.\n" +
    'import type { Patch } from "../stream-types";\n\n' +
    `export const STREAM: Patch[] = [\n${patches.map((p) => "  " + JSON.stringify(p)).join(",\n")},\n];\n`,
);
console.log(`wrote ${patches.length} patches`);
